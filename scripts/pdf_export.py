#!/usr/bin/env python3
"""PDF Export — Generate clean PDF reports of leads and job data.

Usage:
    python -m scripts.pdf_export --leads --output leads_report.pdf
    python -m scripts.pdf_export --jobs --keyword "python" --limit 50
    python -m scripts.pdf_export --analytics
"""
from __future__ import annotations
import json, os, sqlite3, time
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DB = ROOT / "jobs.db"
OUTPUT_DIR = ROOT / "exports"


def get_db():
    return sqlite3.connect(str(DB), timeout=10)


def ensure_output_dir():
    OUTPUT_DIR.mkdir(exist_ok=True)


